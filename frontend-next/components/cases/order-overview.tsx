"use client";

import { Button } from "@/components/ui/button";
import { ExpandableCard } from "@/components/ui/expandable-card";
import { format, parseISO } from "date-fns";
import { AlertTriangle, FileText, Gavel, Loader2 } from "lucide-react";
import { formatHearingDate, todayKey } from "@/lib/utils";
import { latestOrderForOverview, matchesQuery, ordersWithOverview } from "@/lib/case-previews";
import type { CourtOrder, OrderSummary } from "@/types";

interface OrderOverviewProps {
  orders: CourtOrder[];
  /** The case's current next hearing per Court Tracking -- shown instead
   * once the order's own next date has passed. */
  currentNextHearing?: string | null;
  /** Opens the order's PDF (in the document viewer). */
  onViewOrder?: (orderId: number) => void;
  viewingOrderId?: number;
}

function ReadOrderButton({
  order,
  label,
  onViewOrder,
  viewingOrderId,
}: {
  order: CourtOrder;
  label: string;
  onViewOrder?: (orderId: number) => void;
  viewingOrderId?: number;
}) {
  if (!order.has_file) return null;
  return (
    <Button
      variant="secondary"
      size="sm"
      onClick={() => onViewOrder?.(order.id)}
      disabled={viewingOrderId === order.id}
    >
      {viewingOrderId === order.id ? (
        <Loader2 className="h-4 w-4 animate-spin" />
      ) : (
        <FileText className="h-4 w-4" />
      )}
      {label}
    </Button>
  );
}

/** The AI summary of the most recent order, at the top of the case page.
 *
 * Renders nothing until an order has actually been summarised -- a
 * "pending" card on every case would be noise, since the summary is
 * generated by the background worker and simply isn't there yet on a
 * freshly-ingested order. The expanded view lists every order's overview,
 * newest first. */
export function OrderOverviewCard({
  orders,
  currentNextHearing,
  onViewOrder,
  viewingOrderId,
}: OrderOverviewProps) {
  const order = latestOrderForOverview(orders);
  if (!order) return null;

  const summary = order.summary;
  if (!summary || summary.status === "pending") return null;

  const all = ordersWithOverview(orders);

  return (
    <ExpandableCard
      title="Order Overview"
      icon={<Gavel className="h-4 w-4" />}
      titleExtra={
        order.order_date ? (
          <span className="text-xs font-normal text-gray-400">
            {format(parseISO(order.order_date), "d MMM yyyy")}
          </span>
        ) : null
      }
      count={all.length}
      actions={
        <ReadOrderButton
          order={order}
          label="Read the order"
          onViewOrder={onViewOrder}
          viewingOrderId={viewingOrderId}
        />
      }
      // Each order in the list has its own button.
      dialogActions={null}
      viewAll={{ total: all.length, shown: 1 }}
      expandable={all.length > 1}
    >
      {({ expanded, query }) => {
        if (!expanded) {
          return (
            <OrderSummaryBody
              summary={summary}
              currentNextHearing={currentNextHearing}
              layout="split"
            />
          );
        }
        const visible = all.filter((o) =>
          matchesQuery(
            query,
            o.order_number,
            o.description,
            o.summary.what_happened,
            o.order_date ? format(parseISO(o.order_date), "d MMM yyyy") : "undated",
          ),
        );
        if (visible.length === 0) {
          return <p className="text-sm text-gray-500 py-2">No orders match.</p>;
        }
        return (
          <div className="space-y-5">
            {visible.map((o) => (
              <article key={o.id} className="rounded-lg border border-gray-100 p-4">
                <div className="mb-3 flex flex-wrap items-center justify-between gap-2">
                  <h4 className="text-sm font-semibold text-gray-900">
                    Order {o.order_number}
                    <span className="ml-2 text-xs font-normal text-gray-400">
                      {o.order_date ? format(parseISO(o.order_date), "d MMM yyyy") : "Undated"}
                    </span>
                  </h4>
                  <ReadOrderButton
                    order={o}
                    label="Read the order"
                    onViewOrder={onViewOrder}
                    viewingOrderId={viewingOrderId}
                  />
                </div>
                <OrderSummaryBody
                  summary={o.summary}
                  currentNextHearing={currentNextHearing}
                  layout="split"
                />
              </article>
            ))}
          </div>
        );
      }}
    </ExpandableCard>
  );
}

/** The summary body, shared by the case page and the calendar entry.
 *
 * "split" puts the summary and its next date on the left and the
 * directions on the right, once there is room (a container query, so it
 * follows the card's width, not the window's). */
export function OrderSummaryBody({
  summary,
  currentNextHearing,
  layout = "stacked",
}: {
  summary: OrderSummary;
  /** Only the case page passes this; see NextDateLine. */
  currentNextHearing?: string | null;
  layout?: "stacked" | "split";
}) {
  if (summary.status === "failed") {
    return (
      <div className="flex items-start gap-2 text-sm text-status-alert">
        <AlertTriangle className="h-4 w-4 mt-0.5 flex-shrink-0" />
        <div>
          <div className="font-medium">Summary unavailable</div>
          <div className="text-gray-600 mt-0.5">
            The order could not be summarised automatically. Open the order to
            read it.
          </div>
        </div>
      </div>
    );
  }

  if (summary.status === "unreadable") {
    return (
      <div className="flex items-start gap-2 text-sm text-gray-600">
        <AlertTriangle className="h-4 w-4 mt-0.5 flex-shrink-0 text-gray-400" />
        <span>{summary.what_happened}</span>
      </div>
    );
  }

  const nextDate = summary.next_date ? (
    <NextDateLine summary={summary} currentNextHearing={currentNextHearing} />
  ) : null;

  if (layout === "split" && summary.status === "summarized" && hasDirectionsBlock(summary)) {
    return (
      <div className="grid grid-cols-1 gap-4 @lg:grid-cols-2">
        <div className="min-w-0 space-y-4">
          <p className="text-sm text-gray-800">{summary.what_happened}</p>
          {nextDate}
        </div>
        <div className="min-w-0">
          <DirectionsBlock summary={summary} />
        </div>
      </div>
    );
  }

  return (
    <div className="space-y-4">
      <p className="text-sm text-gray-800">{summary.what_happened}</p>

      {summary.status === "summarized" && (
        <DirectionsBlock summary={summary} />
      )}

      {nextDate}
    </div>
  );
}

/** Whether DirectionsBlock has anything to draw. */
function hasDirectionsBlock(summary: OrderSummary): boolean {
  if (summary.your_side_directions !== null) return true;
  return summary.petitioner_directions.length > 0 || summary.respondent_directions.length > 0;
}

/** The order's own "next date". Once that date has passed it's history --
 * the case has moved on, and Court Tracking knows the current date -- so it
 * greys out and points there instead of reading like the upcoming hearing. */
function NextDateLine({
  summary,
  currentNextHearing,
}: {
  summary: OrderSummary;
  currentNextHearing?: string | null;
}) {
  const nextDate = summary.next_date as string;
  const passed = nextDate < todayKey();
  if (!passed) {
    return (
      <div className="pt-3 border-t border-gray-100 text-sm">
        <span className="text-gray-500">Next date: </span>
        <span className="font-medium text-gray-900">{format(parseISO(nextDate), "d MMM yyyy")}</span>
        {summary.next_date_purpose && (
          <span className="text-gray-500"> · {summary.next_date_purpose}</span>
        )}
      </div>
    );
  }
  return (
    <div className="pt-3 border-t border-gray-100 text-sm text-gray-400">
      <span>Next date in this order: </span>
      <span className="line-through">{format(parseISO(nextDate), "d MMM yyyy")}</span>
      <span> (passed)</span>
      {currentNextHearing !== undefined && (
        <span className="text-gray-600">
          {" "}
          ·{" "}
          {currentNextHearing
            ? `Current next hearing: ${formatHearingDate(currentNextHearing)} (Court Tracking)`
            : "See Court Tracking for the current next hearing"}
        </span>
      )}
    </div>
  );
}

/** Directions, foregrounding the advocate's own side when the case's
 * party role is known.
 *
 * When it's "unknown", both sides are shown neutrally and neither is
 * labelled "yours" -- an advocate acting on the opposing side's
 * obligations is exactly the mistake this must not cause. */
function DirectionsBlock({ summary }: { summary: OrderSummary }) {
  const roleKnown = summary.your_side_directions !== null;

  if (roleKnown) {
    const yours = summary.your_side_directions ?? [];
    const theirs = summary.other_side_directions ?? [];

    return (
      <div className="space-y-3">
        <DirectionsList
          label={summary.your_side_label ?? "Your side"}
          directions={yours}
          emphasis
          emptyText="No directions for your side in this order."
        />
        {theirs.length > 0 && (
          <DirectionsList
            label={summary.other_side_label ?? "Other side"}
            directions={theirs}
          />
        )}
      </div>
    );
  }

  const nothingEither =
    summary.petitioner_directions.length === 0 &&
    summary.respondent_directions.length === 0;
  if (nothingEither) return null;

  return (
    <div className="space-y-3">
      <p className="text-xs text-gray-400">
        Your side isn&apos;t recorded for this case, so both sides are shown as
        the order states them. Set it in Case Overview to see your own
        directions first.
      </p>
      <DirectionsList label="Petitioner" directions={summary.petitioner_directions} />
      <DirectionsList label="Respondent" directions={summary.respondent_directions} />
    </div>
  );
}

interface DirectionsListProps {
  label: string;
  directions: string[];
  emphasis?: boolean;
  emptyText?: string;
}

function DirectionsList({
  label,
  directions,
  emphasis,
  emptyText,
}: DirectionsListProps) {
  if (directions.length === 0 && !emptyText) return null;

  return (
    <div
      className={
        emphasis
          ? "rounded-lg border border-accent-soft bg-accent-soft p-3"
          : "rounded-lg border border-gray-100 p-3"
      }
    >
      <div
        className={`text-xs font-semibold uppercase tracking-wide mb-1.5 ${
          emphasis ? "text-accent" : "text-gray-500"
        }`}
      >
        {label}
      </div>
      {directions.length === 0 ? (
        <div className="text-sm text-gray-500">{emptyText}</div>
      ) : (
        <ul className="space-y-1.5">
          {directions.map((direction, i) => (
            <li key={i} className="text-sm text-gray-800 flex gap-2">
              <span className="text-gray-300 flex-shrink-0">•</span>
              <span>{direction}</span>
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}
