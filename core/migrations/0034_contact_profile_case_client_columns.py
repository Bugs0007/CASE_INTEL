"""New columns on three tables that hold real production rows.

  client_contacts    receive_case_updates, receive_payment_reminders,
                     relation_type, relation_name, age, address
  advocate_profiles  advocate_name, phone, reminder_after_days
  cases              client_id (nullable FK -> clients)

Staged the way CLAUDE.md prescribes, following 0032 exactly, so RDS never
sits under a long ACCESS EXCLUSIVE lock:

  NOT NULL columns   ADD COLUMN (nullable, no default)   catalog-only
                     SET DEFAULT                         keeps old code's
                                                         INSERTs valid in
                                                         the deploy window
                     UPDATE ... backfill
                     ADD CONSTRAINT CHECK (IS NOT NULL) NOT VALID
                     VALIDATE CONSTRAINT                 SHARE UPDATE EXCLUSIVE
                     SET NOT NULL                        reuses the proof
                     DROP CONSTRAINT
  cases.client_id    ADD COLUMN NULL                     catalog-only
                     ADD CONSTRAINT ... FK NOT VALID     no scan
                     VALIDATE CONSTRAINT                 SHARE UPDATE EXCLUSIVE
                     CREATE INDEX CONCURRENTLY           no write lock

`atomic = False` is what makes the staging real (see 0032's docstring): in
one transaction the first ALTER's ACCESS EXCLUSIVE lock would be held to the
end. It is also required for CREATE INDEX CONCURRENTLY, which refuses to run
inside a transaction block.

The defaults are left in place after SET NOT NULL, as in 0032 -- Django
supplies the value itself, so they only ever matter to the old code during
the deploy window.

Constraint and index names are the ones Django itself generates for these
fields (read from `sqlmigrate` of the autogenerated equivalent), so later
migrations that alter these fields find them where Django expects.

Re-runnable: every statement is IF [NOT] EXISTS-guarded, because a
non-atomic migration that fails part-way is not recorded as applied and is
simply run again.
"""

from django.core import validators
