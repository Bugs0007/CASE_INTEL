def _staged_not_null(table: str, column: str, sql_type: str, default_sql: str) -> list[str]:
    check = f"{table}_{column}_not_null_chk"
    return [
        f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {column} {sql_type}",
        f"ALTER TABLE {table} ALTER COLUMN {column} SET DEFAULT {default_sql}",
        f"UPDATE {table} SET {column} = {default_sql} WHERE {column} IS NULL",
        f"ALTER TABLE {table} DROP CONSTRAINT IF EXISTS {check}",
        f"ALTER TABLE {table} ADD CONSTRAINT {check} CHECK ({column} IS NOT NULL) NOT VALID",
        f"ALTER TABLE {table} VALIDATE CONSTRAINT {check}",
        f"ALTER TABLE {table} ALTER COLUMN {column} SET NOT NULL",
        f"ALTER TABLE {table} DROP CONSTRAINT {check}",
    ]


def _staged_check(table: str, column: str, expression: str) -> list[str]:
    """A PositiveSmallIntegerField's `>= 0` CHECK, added NOT VALID then
    validated. Named the way Postgres names Django's inline column CHECK."""
    name = f"{table}_{column}_check"
    return [
        f"ALTER TABLE {table} DROP CONSTRAINT IF EXISTS {name}",
        f"ALTER TABLE {table} ADD CONSTRAINT {name} CHECK ({expression}) NOT VALID",
        f"ALTER TABLE {table} VALIDATE CONSTRAINT {name}",
    ]


